"""Structural plugin contracts; implementations need no base class."""
from typing import List, Optional, Protocol
from .types import (ActionReceipt, ArtifactRef, BindingSpec, CandidateContext,
                    CandidateFeedback, CandidateOutput, DataViewRef,
                    EnvironmentCommand, EnvironmentDescription, ObservationBatch,
                    ObservationRequest, TaskEffect, TaskExecutionContext,
                    TaskInput, TaskSpec, TaskUpdate)


class Environment(Protocol):
    def describe(self) -> EnvironmentDescription: ...
    def start(self, spec: dict) -> dict: ...
    def observe(self, request: ObservationRequest) -> ObservationBatch: ...
    def act(self, command: EnvironmentCommand) -> ActionReceipt: ...
    def finish(self) -> dict: ...


class TaskSession(Protocol):
    def next_observation(self) -> ObservationRequest: ...
    def consume(self, batch: ObservationBatch) -> TaskUpdate: ...
    def on_action(self, receipt: ActionReceipt) -> TaskUpdate: ...
    def interpret(self, task_input: TaskInput, output: CandidateOutput,
                  output_id: str) -> TaskEffect: ...
    def finish(self, reason: str) -> dict: ...


class Task(Protocol):
    def describe(self) -> dict: ...
    def bind(self, spec: TaskSpec, binding: BindingSpec,
             environment: EnvironmentDescription,
             execution: TaskExecutionContext) -> TaskSession: ...


class Candidate(Protocol):
    def prepare(self, context: CandidateContext,
                training: Optional[DataViewRef]) -> dict: ...
    def infer(self, task_input: TaskInput) -> CandidateOutput: ...
    def update(self, feedback: CandidateFeedback) -> dict: ...
    def finish(self) -> List[ArtifactRef]: ...


class Scorer(Protocol):
    def score(self, results: dict, outcomes: dict, context: dict) -> dict: ...


class TraceCollector(Protocol):
    """Optional injected collector; no profile is claimed by the base runtime."""
    def bind(self, run_id: str, task_input: TaskInput, output_id: str) -> None: ...
    def flush(self) -> List[dict]: ...

